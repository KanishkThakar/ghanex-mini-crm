export interface Toast {
  id: number;
  message: string;
  tone: 'success' | 'error';
}

export function Toasts({ toasts }: { toasts: Toast[] }) {
  return (
    <div className="toasts" role="status" aria-live="polite">
      {toasts.map((t) => (
        <div key={t.id} className={`toast toast--${t.tone}`}>
          {t.message}
        </div>
      ))}
    </div>
  );
}
